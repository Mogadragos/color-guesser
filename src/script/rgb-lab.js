const lab2rgb = function (t) {
    var a,
        h,
        M,
        r = (t[0] + 16) / 116,
        o = t[1] / 500 + r,
        n = r - t[2] / 200;
    return (
        (h =
            -0.9689 *
                (o =
                    0.95047 *
                    (o * o * o > 0.008856
                        ? o * o * o
                        : (o - 16 / 116) / 7.787)) +
            1.8758 *
                (r =
                    1 *
                    (r * r * r > 0.008856
                        ? r * r * r
                        : (r - 16 / 116) / 7.787)) +
            0.0415 *
                (n =
                    1.08883 *
                    (n * n * n > 0.008856
                        ? n * n * n
                        : (n - 16 / 116) / 7.787))),
        (M = 0.0557 * o + -0.204 * r + 1.057 * n),
        (a =
            (a = 3.2406 * o + -1.5372 * r + -0.4986 * n) > 0.0031308
                ? 1.055 * Math.pow(a, 1 / 2.4) - 0.055
                : 12.92 * a),
        (h = h > 0.0031308 ? 1.055 * Math.pow(h, 1 / 2.4) - 0.055 : 12.92 * h),
        (M = M > 0.0031308 ? 1.055 * Math.pow(M, 1 / 2.4) - 0.055 : 12.92 * M),
        [
            255 * Math.max(0, Math.min(1, a)),
            255 * Math.max(0, Math.min(1, h)),
            255 * Math.max(0, Math.min(1, M)),
        ]
    );
};
const rgb2lab = function (t) {
    var a,
        h,
        M,
        r = t[0] / 255,
        o = t[1] / 255,
        n = t[2] / 255;
    return (
        (h =
            (0.2126 *
                (r =
                    r > 0.04045
                        ? Math.pow((r + 0.055) / 1.055, 2.4)
                        : r / 12.92) +
                0.7152 *
                    (o =
                        o > 0.04045
                            ? Math.pow((o + 0.055) / 1.055, 2.4)
                            : o / 12.92) +
                0.0722 *
                    (n =
                        n > 0.04045
                            ? Math.pow((n + 0.055) / 1.055, 2.4)
                            : n / 12.92)) /
            1),
        (M = (0.0193 * r + 0.1192 * o + 0.9505 * n) / 1.08883),
        (a =
            (a = (0.4124 * r + 0.3576 * o + 0.1805 * n) / 0.95047) > 0.008856
                ? Math.pow(a, 1 / 3)
                : 7.787 * a + 16 / 116),
        [
            116 *
                (h = h > 0.008856 ? Math.pow(h, 1 / 3) : 7.787 * h + 16 / 116) -
                16,
            500 * (a - h),
            200 *
                (h -
                    (M =
                        M > 0.008856
                            ? Math.pow(M, 1 / 3)
                            : 7.787 * M + 16 / 116)),
        ]
    );
};
const deltaE = function (t, a) {
    var h = t[0] - a[0],
        M = t[1] - a[1],
        r = t[2] - a[2],
        o = Math.sqrt(t[1] * t[1] + t[2] * t[2]),
        n = o - Math.sqrt(a[1] * a[1] + a[2] * a[2]),
        p = M * M + r * r - n * n,
        w = h / 1,
        e = n / (1 + 0.045 * o),
        s = (p = p < 0 ? 0 : Math.sqrt(p)) / (1 + 0.015 * o),
        i = w * w + e * e + s * s;
    return i < 0 ? 0 : Math.sqrt(i);
};
